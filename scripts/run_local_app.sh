#!/usr/bin/env bash
# Run the whole app locally for testing: FastAPI backend on :8080 and the
# Strategy Control Room (Vite) on :18936, with /api proxied to the backend.
#
#   bash scripts/run_local_app.sh            # API + dashboard, no workers
#   LOCAL_WORKERS=true bash scripts/run_local_app.sh   # also Celery workers + beat
#
# Paper only (ALLOW_LIVE_TRADING=false). Uses its own SQLite database
# (artifacts/api-server/backend/local_app.db), never the Replit databases.
# Role keys for the four roles are generated once into .local-app.env
# (gitignored); paste the admin key into the dashboard's key field to act as
# admin, or browse read-only as the anonymous viewer.
# Broker calls need DEV_PAPER_ALPACA_API_KEY / _SECRET / DEV_PAPER_BROKER_ACCOUNT_ID
# in .local-app.env; without them the app runs and the broker panels report
# that no paper account is bound.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
backend="$root/artifacts/api-server/backend"
frontend="$root/artifacts/strategy-control-room"
env_file="$root/.local-app.env"

if [[ ! -x "$root/.venv/bin/python3.11" ]]; then
  echo "Missing $root/.venv (python 3.11 with the backend requirements)." >&2
  exit 1
fi
export PATH="$root/.venv/bin:$PATH"

if [[ ! -f "$env_file" ]]; then
  {
    echo "# Generated by scripts/run_local_app.sh; local only, never commit."
    for role in VIEWER RESEARCHER OPERATOR ADMIN; do
      echo "AUTH_${role}_KEY=$(python3.11 -c 'import secrets; print(secrets.token_urlsafe(36))')"
    done
  } > "$env_file"
  chmod 600 "$env_file"
  echo "Wrote role keys to $env_file"
fi
set -a
# shellcheck disable=SC1090
source "$env_file"
set +a

export ENVIRONMENT=local
export ALLOW_LIVE_TRADING=false
export ALLOW_ANONYMOUS_VIEWER="${ALLOW_ANONYMOUS_VIEWER:-true}"
export DATABASE_URL="${DATABASE_URL:-sqlite:///$backend/local_app.db}"
export PAPER_WORKERS_ENABLED="${LOCAL_WORKERS:-false}"
api_port="${API_PORT:-8080}"
web_port="${WEB_PORT:-18936}"

pids=()
cleanup() {
  trap - EXIT INT TERM
  for pid in "${pids[@]}"; do kill -TERM "$pid" 2>/dev/null || true; done
  wait 2>/dev/null || true
}
trap cleanup EXIT INT TERM

(cd "$backend" && PORT="$api_port" bash scripts/run_local_stack.sh) &
pids+=("$!")

for _ in $(seq 1 120); do
  if curl -sf "http://127.0.0.1:$api_port/api/health" >/dev/null 2>&1; then break; fi
  sleep 1
done
curl -sf "http://127.0.0.1:$api_port/api/health" >/dev/null || echo "Backend did not answer /api/health yet; starting the dashboard anyway." >&2

(cd "$frontend" && PORT="$web_port" BASE_PATH=/ API_PROXY_TARGET="http://127.0.0.1:$api_port" \
  ./node_modules/.bin/vite --config vite.config.ts --host 127.0.0.1) &
pids+=("$!")

echo "Dashboard: http://127.0.0.1:$web_port   API: http://127.0.0.1:$api_port/api"
if (( BASH_VERSINFO[0] > 4 || (BASH_VERSINFO[0] == 4 && BASH_VERSINFO[1] >= 3) )); then
  wait -n "${pids[@]}"
else
  # bash < 4.3 (macOS /bin/bash 3.2) has no `wait -n`: poll until any process exits.
  while :; do
    for pid in "${pids[@]}"; do
      kill -0 "$pid" 2>/dev/null || break 2
    done
    sleep 2
  done
fi
echo "A local app process exited; stopping the rest." >&2
exit 1
